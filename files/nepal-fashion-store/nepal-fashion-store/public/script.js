// ======================================================
// LOAD PRODUCTS
// ======================================================

function loadProducts() {

  const productGrid =
    document.getElementById("product-grid");

  const loadingMsg =
    document.getElementById("loading-msg");


  if (!productGrid) {

    console.error(
      "Product grid was not found."
    );

    return;
  }


  if (loadingMsg) {

    loadingMsg.style.display = "none";

  }


  productGrid.innerHTML = "";


  products.forEach(function(product) {

    const productCard =
      document.createElement("div");


    productCard.className =
      "product-card";


    productCard.innerHTML = `

      <img
        src="${product.image}"
        alt="${product.title}"
        class="product-image"
        onerror="this.src='https://via.placeholder.com/600x600?text=Image+Unavailable'"
      >

      <div class="product-info">

        <h4>
          ${product.title}
        </h4>

        <p class="price">
          NPR ${product.price.toLocaleString("en-NP")}
        </p>

        <button
          onclick="addToCart(${product.id})"
        >
          Add to Cart
        </button>

      </div>

    `;


    productGrid.appendChild(
      productCard
    );

  });

}


// ======================================================
// GET CART
// ======================================================

function getCart() {

  const cart =
    localStorage.getItem("cart");


  if (!cart) {

    return [];

  }


  try {

    return JSON.parse(cart);

  } catch (error) {

    console.error(
      "Error reading cart:",
      error
    );

    return [];

  }

}


// ======================================================
// SAVE CART
// ======================================================

function saveCart(cart) {

  localStorage.setItem(
    "cart",
    JSON.stringify(cart)
  );

}


// ======================================================
// ADD PRODUCT TO CART
// ======================================================

function addToCart(productId) {

  const product =
    products.find(function(item) {

      return item.id === productId;

    });


  if (!product) {

    console.error(
      "Product not found:",
      productId
    );

    return;

  }


  const cart =
    getCart();


  const existingProduct =
    cart.find(function(item) {

      return item.id === productId;

    });


  if (existingProduct) {

    existingProduct.quantity += 1;

  } else {

    cart.push({

      id: product.id,

      title: product.title,

      price: product.price,

      image: product.image,

      quantity: 1

    });

  }


  saveCart(cart);


  updateCartCount();


  alert(
    product.title +
    " added to cart!"
  );

}


// ======================================================
// UPDATE CART COUNT
// ======================================================

function updateCartCount() {

  const cartCount =
    document.getElementById(
      "cart-count"
    );


  if (!cartCount) {

    return;

  }


  const cart =
    getCart();


  let totalQuantity = 0;


  cart.forEach(function(item) {

    totalQuantity +=
      Number(item.quantity) || 0;

  });


  cartCount.textContent =
    totalQuantity;

}


// ======================================================
// RENDER CART
// ======================================================

function renderCart() {

  const cartContainer =
    document.getElementById(
      "cart-items"
    );


  const cartTotal =
    document.getElementById(
      "cart-total"
    );


  if (!cartContainer) {

    return;

  }


  const cart =
    getCart();


  cartContainer.innerHTML = "";


  if (cart.length === 0) {

    cartContainer.innerHTML = `

      <p>
        Your cart is empty.
      </p>

    `;


    if (cartTotal) {

      cartTotal.textContent =
        "NPR 0";

    }


    return;

  }


  let total = 0;


  cart.forEach(function(item) {

    const itemTotal =
      item.price *
      item.quantity;


    total += itemTotal;


    const cartItem =
      document.createElement("div");


    cartItem.className =
      "cart-item";


    cartItem.innerHTML = `

      <div class="cart-item-image">

        <img
          src="${item.image}"
          alt="${item.title}"
          onerror="this.src='https://via.placeholder.com/200x200?text=Image+Unavailable'"
        >

      </div>


      <div class="cart-item-info">

        <h4>
          ${item.title}
        </h4>

        <p>
          NPR ${item.price.toLocaleString("en-NP")}
        </p>


        <div class="quantity-controls">

          <button
            onclick="changeQty(${item.id}, -1)"
          >
            -
          </button>


          <span>
            ${item.quantity}
          </span>


          <button
            onclick="changeQty(${item.id}, 1)"
          >
            +
          </button>

        </div>


        <p>
          Subtotal:
          NPR ${itemTotal.toLocaleString("en-NP")}
        </p>


        <button
          class="remove-btn"
          onclick="removeFromCart(${item.id})"
        >
          Remove
        </button>

      </div>

    `;


    cartContainer.appendChild(
      cartItem
    );

  });


  if (cartTotal) {

    cartTotal.textContent =
      "NPR " +
      total.toLocaleString("en-NP");

  }

}


// ======================================================
// CHANGE PRODUCT QUANTITY
// ======================================================

function changeQty(
  productId,
  change
) {

  const cart =
    getCart();


  const item =
    cart.find(function(product) {

      return product.id === productId;

    });


  if (!item) {

    return;

  }


  item.quantity += change;


  if (item.quantity <= 0) {

    const updatedCart =
      cart.filter(function(product) {

        return product.id !== productId;

      });


    saveCart(
      updatedCart
    );

  } else {

    saveCart(
      cart
    );

  }


  updateCartCount();


  renderCart();

}


// ======================================================
// REMOVE PRODUCT FROM CART
// ======================================================

function removeFromCart(productId) {

  const cart =
    getCart();


  const updatedCart =
    cart.filter(function(item) {

      return item.id !== productId;

    });


  saveCart(
    updatedCart
  );


  updateCartCount();


  renderCart();

}


// ======================================================
// CHECKOUT SUMMARY
// ======================================================

function showCheckoutSummary() {

  const summaryContainer =
    document.getElementById(
      "checkout-summary"
    );


  if (!summaryContainer) {

    return;

  }


  const cart =
    getCart();


  summaryContainer.innerHTML = "";


  if (cart.length === 0) {

    summaryContainer.innerHTML = `

      <p>
        Your cart is empty.
      </p>

    `;


    return;

  }


  let total = 0;


  cart.forEach(function(item) {

    const itemTotal =
      item.price *
      item.quantity;


    total += itemTotal;


    const summaryItem =
      document.createElement("div");


    summaryItem.className =
      "checkout-item";


    summaryItem.innerHTML = `

      <span>
        ${item.title}
        ×
        ${item.quantity}
      </span>

      <span>
        NPR ${itemTotal.toLocaleString("en-NP")}
      </span>

    `;


    summaryContainer.appendChild(
      summaryItem
    );

  });


  const totalElement =
    document.createElement("div");


  totalElement.className =
    "checkout-total";


  totalElement.innerHTML = `

    <strong>
      Total:
    </strong>

    <strong>
      NPR ${total.toLocaleString("en-NP")}
    </strong>

  `;


  summaryContainer.appendChild(
    totalElement
  );

}


// ======================================================
// PLACE ORDER
// ======================================================

async function placeOrder() {

  const cart = getCart();


  if (cart.length === 0) {

    alert(
      "Your cart is empty. Add some products first."
    );

    return;

  }


  const token =
    localStorage.getItem("token");


  if (!token) {

    alert(
      "Please login before placing an order."
    );

    window.location.href =
      "login.html";

    return;

  }


  const name =
    document.getElementById(
      "fullname"
    ).value.trim();


  const phone =
    document.getElementById(
      "phone"
    ).value.trim();


  const address =
    document.getElementById(
      "address"
    ).value.trim();


  const city =
    document.getElementById(
      "city"
    ).value.trim();


  const paymentMethod =
    document.getElementById(
      "payment"
    ).value;


  // ====================================================
  // IMPORTANT:
  // Cart uses:
  // item.id
  // item.title
  // item.price
  // item.quantity
  //
  // So we send those exact values to the backend.
  // ====================================================

  const items =
    cart.map(function(item) {

      return {

        productId:
          Number(item.id),

        productName:
          item.title,

        price:
          Number(item.price),

        quantity:
          Number(item.quantity)

      };

    });


  console.log(
    "Sending order items:",
    items
  );


  try {

    const response =
      await fetch(
        "/api/orders",
        {
          method: "POST",

          headers: {

            "Content-Type":
              "application/json",

            "Authorization":
              "Bearer " + token

          },

          body:
            JSON.stringify({

              customerName:
                name,

              phone:
                phone,

              address:
                address,

              city:
                city,

              paymentMethod:
                paymentMethod,

              items:
                items

            })

        }
      );


    const data =
      await response.json();


    if (!response.ok) {

      console.error(
        "Order failed:",
        data
      );

      alert(
        data.message ||
        "Could not place order."
      );

      return;

    }


    const confirmationEl =
      document.getElementById(
        "order-confirmation"
      );


    if (confirmationEl) {

      confirmationEl.style.display =
        "block";


      confirmationEl.textContent =
        "Thank you " +
        name +
        "! Your order (" +
        data.orderNumber +
        ") has been placed successfully.";

    }


    const checkoutForm =
      document.getElementById(
        "checkout-form"
      );


    if (checkoutForm) {

      checkoutForm.style.display =
        "none";

    }


    // Clear the SAME cart key used by getCart()
    localStorage.removeItem(
      "cart"
    );


    updateCartCount();


    showCheckoutSummary();


  } catch (error) {

    console.error(
      "Order error:",
      error
    );


    alert(
      "Could not connect to the server. Please try again."
    );

  }

}


